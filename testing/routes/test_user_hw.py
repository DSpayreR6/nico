#!/usr/bin/env python3
"""Benutzername und Hardware-Import – ohne Browser.

Deckt die beiden Fehler vom 2026-10-23 ab (frische VM, NiCo 0.12.0):

1. Die erzeugte configuration.nix band hardware-configuration.nix nie ein.
   Rebuild: "The 'fileSystems' option does not specify your root file system."
   Im Flake-Modus fiel das nie auf, weil dort der Host-Body in flake.nix den
   Import trägt – deshalb steht hier die komplette Matrix, inklusive Wechsel
   zwischen den Modi.

2. Der Benutzername bekam bei jedem Speichern eine Quoting-Schicht dazu:
   nico -> "nico" -> "\\"nico\\"" -> ... Rebuild: "The username ... is not valid".

Lauf: nix-shell shell.nix --run "python testing/routes/test_user_hw.py"
"""
import copy
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from nico import config_manager as cm, generator, importer, validator  # noqa: E402

fails: list[str] = []


def check(label, cond, got=None):
    print(("  OK   " if cond else "  FAIL ") + label
          + ("" if cond or got is None else f"  (war: {got})"))
    if not cond:
        fails.append(label)


def base_data(**kw):
    data = copy.deepcopy(cm.DEFAULT_NIXOS_CONFIG)
    data["username"] = "nico"
    data["system_state_version"] = "25.05"
    data.update(kw)
    return data


def user_lines(text):
    return [l.strip() for l in text.splitlines() if "users.users." in l]


def imports_lines(text):
    return [l.strip() for l in text.splitlines() if re.match(r'\s*imports\s*=', l)]


# ── 1 Hardware-Import: die vier Fälle einzeln ────────────────────────────────
print("1. Hardware-Import pro Modus")

co_noflake = generator.generate_configuration_nix(
    base_data(flakes=False, hardware_config=True))
check("Nicht-Flake: configuration.nix bindet die Hardware-Config ein",
      "./hardware-configuration.nix" in co_noflake, imports_lines(co_noflake))

co_flake = generator.generate_configuration_nix(
    base_data(flakes=True, hardware_config=True))
check("Flake: configuration.nix bindet sie NICHT ein (flake.nix tut es)",
      "hardware-configuration" not in co_flake, imports_lines(co_flake))

flake_nix = generator.generate_flake_nix(
    base_data(flakes=True, hardware_config=True, flake_hosts=[{"name": "vm"}]))
check("Flake: flake.nix bindet sie pro Host ein",
      "./hosts/vm/hardware-configuration.nix" in flake_nix)

co_nohw = generator.generate_configuration_nix(
    base_data(flakes=False, hardware_config=False))
check("Nicht-Flake ohne Hardware-Config: kein Import",
      "hardware-configuration" not in co_nohw, imports_lines(co_nohw))

# ── 2 Moduswechsel in beide Richtungen ───────────────────────────────────────
print("\n2. Wechsel zwischen Nicht-Flake und Flake")

data = base_data(flakes=False, hardware_config=True)
step1 = generator.generate_configuration_nix(data)
data["flakes"] = True
step2 = generator.generate_configuration_nix(data)
data["flakes"] = False
step3 = generator.generate_configuration_nix(data)

check("Schritt 1 (Nicht-Flake): Import da", "hardware-configuration" in step1)
check("Schritt 2 (auf Flake): Import verschwindet",
      "hardware-configuration" not in step2, imports_lines(step2))
check("Schritt 3 (zurück): Import kommt wieder", "hardware-configuration" in step3)
check("Wechsel verliert keine Daten",
      all("users.users.nico" in s for s in (step1, step2, step3)))

# ── 3 Kein zweites imports-Attribut neben einem Brick ────────────────────────
print("\n3. Vorhandenes imports im Brick")

with_brick = base_data(flakes=False, hardware_config=True, brick_blocks={
    "imports": {
        "section": "HEAD", "order": 1,
        "text": "# <brick: HEAD / #1 imports>\n"
                "imports = [ ./hardware-configuration.nix ];\n"
                "# </brick: imports>\n",
    },
})
out = generator.generate_configuration_nix(with_brick)
check("genau ein imports-Attribut, nicht zwei",
      len(imports_lines(out)) == 1, imports_lines(out))

# ── 4 Benutzername über mehrere Speichervorgänge ─────────────────────────────
print("\n4. Benutzername bleibt über Roundtrips stabil")

TPL = """# Generated by NiCo
{ config, pkgs, lib, ... }: {
  system.stateVersion = "25.05";
%s
    isNormalUser = true;
    description = "nico";
  };
}
"""

for label, first in (("unquotiert", "  users.users.nico = {"),
                     ("quotiert",   '  users.users."nico" = {'),
                     ("bereits beschädigt", r'  users.users."\"\\\"nico\\\"\"" = {')):
    src = TPL % first
    seen = []
    for _ in range(4):
        parsed = importer.parse_config(src)
        seen.append(parsed.get("username"))
        d = base_data()
        d.update(parsed)
        src = generator.generate_configuration_nix(d)
    check(f"{label}: Name bleibt über 4 Runden 'nico'",
          seen == ["nico"] * 4, seen)
    check(f"{label}: erzeugte Zeile ohne Quotes",
          user_lines(src)[0].startswith("users.users.nico ="), user_lines(src)[:1])

# ── 5 Validator ──────────────────────────────────────────────────────────────
print("\n5. Validator-Regeln")

HW = ('{ config, lib, pkgs, modulesPath, ... }:\n{\n'
      '  fileSystems."/" = { device = "/dev/sda1"; fsType = "ext4"; };\n}\n')
ALL_ON = {r.id: True for r in validator.ALL_RULES}


def findings_for(files: dict, config: dict, host=None) -> dict:
    """Write files into a temp config dir and run all rules on it."""
    with tempfile.TemporaryDirectory() as tmp:
        for name, text in files.items():
            p = Path(tmp) / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
        out: dict = {}
        for f in validator.run_validation(tmp, ALL_ON, config, host):
            out.setdefault(f["rule_id"], []).append(f)
        return out


# 5a – Hardware-Config liegt da, wird aber nicht eingebunden
got = findings_for(
    {"configuration.nix": generator.generate_configuration_nix(
        base_data(flakes=False, hardware_config=False)),
     "hardware-configuration.nix": HW},
    base_data())
check("hardware_imported meldet den fehlenden Import",
      "hardware_imported" in got, sorted(got))
check("hardware_imported ist ein Fehler, keine Warnung",
      got.get("hardware_imported", [{}])[0].get("severity") == "error",
      got.get("hardware_imported"))

# 5b – derselbe Import, aber als Brick: keine Falschmeldung
got = findings_for(
    {"configuration.nix": generator.generate_configuration_nix(with_brick),
     "hardware-configuration.nix": HW},
    base_data())
check("hardware_imported schweigt, wenn das imports im Brick steht",
      "hardware_imported" not in got, sorted(got))

# 5c – Flake erwartet die Datei im Host-Verzeichnis, sie liegt in der Wurzel
flake_cfg = base_data(flakes=True, hardware_config=True, flake_hosts=[{"name": "vm"}])
got = findings_for(
    {"configuration.nix": generator.generate_configuration_nix(flake_cfg),
     "flake.nix": generator.generate_flake_nix(flake_cfg),
     "hardware-configuration.nix": HW,
     "hosts/vm/default.nix": "{ ... }:\n{\n}\n"},
    flake_cfg)
check("hardware_host_location meldet die Datei am falschen Ort",
      "hardware_host_location" in got, sorted(got))

# 5d – dieselbe Lage, aber die Datei liegt richtig
got = findings_for(
    {"configuration.nix": generator.generate_configuration_nix(flake_cfg),
     "flake.nix": generator.generate_flake_nix(flake_cfg),
     "hardware-configuration.nix": HW,
     "hosts/vm/hardware-configuration.nix": HW,
     "hosts/vm/default.nix": "{ ... }:\n{\n}\n"},
    flake_cfg)
check("hardware_host_location schweigt, wenn sie im Host-Verzeichnis liegt",
      "hardware_host_location" not in got, sorted(got))
check("hardware_imported schweigt bei einem Flake-Host",
      "hardware_imported" not in got, sorted(got))

# 5e – Benutzername
for name, ok in (("nico", True), ("nico2", True), ("_test", True),
                 ('"nico"', False), ("Nico", False), ("1nico", False),
                 ("nico user", False)):
    cfg = base_data(username=name)
    got = findings_for(
        {"configuration.nix": generator.generate_configuration_nix(cfg)}, cfg)
    hit = "user_name_valid" in got
    check(f"user_name_valid: {name!r} {'gültig' if ok else 'ungültig'}",
          hit is (not ok), got.get("user_name_valid"))

cfg = base_data(extra_users=[{"username": "gäst"}])
got = findings_for({"configuration.nix": generator.generate_configuration_nix(cfg)}, cfg)
check("user_name_valid prüft auch Zusatzbenutzer", "user_name_valid" in got, sorted(got))

print("\n" + ("ALLE PRÜFUNGEN BESTANDEN" if not fails else f"FEHLGESCHLAGEN: {fails}"))
sys.exit(1 if fails else 0)
