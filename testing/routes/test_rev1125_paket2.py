#!/usr/bin/env python3
"""Revision 2026-11-25, Paket 2: ein gemeinsamer Weg durch die Config (S1, S2).

Bis 2026-11-26 liefen etwa zwanzig Stellen selbst durch das Config-
Verzeichnis, jede mit eigenen Regeln. Ablösen und Kategorisieren folgten
dabei einer Verknüpfung nach außen und schrieben in die Datei am anderen
Ende (S1), die Formatprüfung las sie und konnte die eigene Config sperren
(S2), der Validator las sie ebenfalls. Jetzt läuft alles über
configfiles.scan()/nix_files(): versteckte Verzeichnisse und Links nach
außen bleiben draußen, und was eine Aktion nicht erfasst, liefert
/api/config/left-out für das Fenster vor der Aktion (Martin 2026-11-26).

Lauf: nix-shell shell.nix --run "python testing/routes/test_rev1125_paket2.py"
"""
import io, json, os, re, sys, tempfile, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

xdg = Path(tempfile.mkdtemp(prefix="nico-xdg-"))
os.environ["XDG_CONFIG_HOME"] = str(xdg)
cfg = Path(tempfile.mkdtemp(prefix="nico-cfg-"))
ext = Path(tempfile.mkdtemp(prefix="nico-ext-"))
(xdg / "nico").mkdir(parents=True)
(xdg / "nico" / "settings.json").write_text(
    json.dumps({"nixos_config_dir": str(cfg), "language": "de", "git_sync": False}),
    encoding="utf-8")
(cfg / "config.json").write_text(json.dumps({"hosts_dir": "hosts"}), encoding="utf-8")

from nico import configfiles, importer, server, validator  # noqa: E402

fails = []
def check(label, cond, got=None):
    print(("  OK   " if cond else "  FAIL ") + label + ("" if cond or got is None else f"  (war: {got})"))
    if not cond: fails.append(label)

# ── Aufbau ──────────────────────────────────────────────────────────────────
(cfg / "modules").mkdir()
(cfg / ".git").mkdir()
(cfg / ".git" / "x.nix").write_text("{ }\n")
(cfg / "configuration.nix").write_text(
    "{ ... }: {\n"
    "  imports = [ ./modules/a.nix /etc/nixos/hardware-configuration.nix ../shared/x.nix ];\n"
    "  fileSystems.\"/home\".device = \"/dev/sda1\";\n"
    "  # /etc/kommentar.nix\n"
    "  x = a // b;\n  y = 1/2;\n"
    "  s = \"${pkgs.writeShellScript \"w\" ''\n    busctl /org/freedesktop/x 2>/dev/null\n  ''}\";\n"
    "}\n", encoding="utf-8")
(cfg / "modules" / "a.nix").write_text("{ ... }: { }\n", encoding="utf-8")
(cfg / "modules" / "inner.nix").symlink_to("a.nix")         # relative, inside
SECRET = "# Generated by NiCo\n# nico-version: 0.1.0 #f9\n{ geheim = true; }\n"
(ext / "secret.nix").write_text(SECRET, encoding="utf-8")
(cfg / "modules" / "secret.nix").symlink_to(ext / "secret.nix")
(ext / "dir").mkdir()
(ext / "dir" / "z.nix").write_text("{ }\n")
(cfg / "shared").symlink_to(ext / "dir")
(ext / "hl.nix").write_text("{ }\n")
os.link(ext / "hl.nix", cfg / "modules" / "hl.nix")

# ── 1. scan / nix_files ─────────────────────────────────────────────────────
print("1. Der gemeinsame Weg")
s = configfiles.scan(cfg, refs=True)
rels = s.rels()
check("eigene Dateien erfasst", {"configuration.nix", "modules/a.nix", "modules/inner.nix"} <= set(rels), rels)
check(".git nicht durchlaufen", not any(r.startswith(".git") for r in rels), rels)
check("Link nach außen nicht erfasst", "modules/secret.nix" not in rels, rels)
check("verlinktes Verzeichnis nach außen nicht durchlaufen", not any(r.startswith("shared/") for r in rels), rels)
kinds = {(x.file, x.kind) for x in s.left}
check("Link nach außen gemeldet", ("modules/secret.nix", "link_out") in kinds, kinds)
check("Verzeichnis-Link nach außen gemeldet", ("shared", "link_out") in kinds, kinds)
check("harter Link gemeldet und erfasst",
      ("modules/hl.nix", "hardlink") in kinds and "modules/hl.nix" in rels, kinds)
paths = {(x.target, x.line) for x in s.left if x.kind == "nix_path"}
check("Pfad im Code: /etc/nixos/… mit Zeile", ("/etc/nixos/hardware-configuration.nix", 2) in paths, paths)
check("Pfad im Code: ../shared/x.nix", ("../shared/x.nix", 2) in paths, paths)
check("nicht gemeldet: ./modules/a.nix, Strings, Kommentar, //, 1/2, verschachtelte Strings",
      len(paths) == 2, paths)
check("nix_files: gleiche Dateien, Pfade ab dem übergebenen Verzeichnis",
      configfiles.nix_files(str(cfg)) == [cfg / r for r in rels if r.endswith(".nix")])
check("nix_files mit Unterverzeichnis",
      configfiles.nix_files(cfg, cfg / "modules") == [cfg / "modules/a.nix", cfg / "modules/hl.nix",
                                                       cfg / "modules/inner.nix"],
      configfiles.nix_files(cfg, cfg / "modules"))

print("\n   Verschieben")
m = configfiles.scan(cfg, nix_only=False, move=True, refs=True)
(cfg / "modules" / "abs_in.nix").symlink_to(cfg / "modules" / "a.nix")
(cfg / "rel_out.nix").symlink_to(os.path.relpath(ext / "dir" / "z.nix", cfg))
(cfg / "modules" / "abs.nix").write_text(f"{{ imports = [ {cfg}/modules/a.nix ]; }}\n")
m = configfiles.scan(cfg, nix_only=False, move=True, refs=True)
mk = {(x.file, x.kind) for x in m.left}
check("absoluter Link nach innen bricht beim Verschieben", ("modules/abs_in.nix", "link_breaks") in mk, mk)
check("relativer Link nach außen gemeldet", ("rel_out.nix", "link_out") in mk, mk)
check("absoluter Pfad im Code nach innen bricht", ("modules/abs.nix", "path_breaks") in mk, mk)
check("relativer Link nach innen bricht nicht", ("modules/inner.nix", "link_breaks") not in mk, mk)
for p in ("modules/abs_in.nix", "rel_out.nix", "modules/abs.nix"):
    (cfg / p).unlink()

# ── 2. Schnittstelle ────────────────────────────────────────────────────────
print("\n2. /api/config/left-out")
client = server.create_app().test_client()
page = client.get("/").get_data(as_text=True)
csrf = re.search(r'<meta name="csrf-token" content="([^"]+)"', page).group(1)
H = {"X-CSRF-Token": csrf, "Content-Type": "application/json"}
r = client.get("/api/config/left-out?all=1").get_json()
lk = {(x["file"], x["kind"]) for x in r.get("left", [])}
check("liefert Links, harte Links und Pfade", {("modules/secret.nix", "link_out"),
      ("modules/hl.nix", "hardlink")} <= lk and any(k == "nix_path" for _, k in lk), lk)

# ── 3. S2: Formatprüfung ────────────────────────────────────────────────────
print("\n3. S2: Formatprüfung liest keine Datei außerhalb")
r = client.get("/api/format/check").get_json()
check("verlinkte #f9-Datei sperrt nicht", r.get("too_new") == [], r)
s_, j = client.post("/api/categorize", headers=H).status_code, None
check("Schreibsperre greift nicht (Kategorisieren läuft)", s_ == 200, s_)

# ── 4. S1: Kategorisieren und Ablösen ───────────────────────────────────────
print("\n4. S1: Kategorisieren und Ablösen schreiben nicht nach außen")
check("Kategorisieren: Datei außerhalb bytegleich", (ext / "secret.nix").read_text() == SECRET)
check("… Link noch da", (cfg / "modules" / "secret.nix").is_symlink())

name = importer.backup_to_zip(cfg)
with zipfile.ZipFile(cfg / name) as z:
    names, comment = z.namelist(), z.comment.decode()
check("Backup-ZIP ohne Datei außerhalb", "modules/secret.nix" not in names, names)
check("… mit eigener Datei", "modules/a.nix" in names, names)
check("… nennt den Link im Kommentar", "modules/secret.nix" in comment, comment)
(cfg / name).unlink()

r = client.post("/api/config/detach", headers=H)
check("Ablösen gelingt", r.status_code == 200, r.get_json())
check("Ablösen: Datei außerhalb bytegleich", (ext / "secret.nix").read_text() == SECRET)
check("… Link noch da", (cfg / "modules" / "secret.nix").is_symlink())

# ── 5. Validator ────────────────────────────────────────────────────────────
print("\n5. Validator nutzt denselben Weg")
check("keine eigene rglob-Schleife mehr über die Config",
      ".rglob(\"*.nix\")" not in Path(validator.__file__).read_text().replace(
          '(source / "nixos" / "modules").rglob("*.nix")', ""))

print()
if fails:
    print(f"{len(fails)} FEHLER")
    sys.exit(1)
print("Alles grün.")
