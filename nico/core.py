def classify_filename(name: str) -> str | None:
    """Map a .nix filename to its NiCo type code. Returns None for non-.nix files."""
    if name in ('configuration.nix', 'default.nix'):
        return 'co'
    if name == 'flake.nix':
        return 'fl'
    if name == 'hardware-configuration.nix':
        return 'hw'
    if name == 'home.nix':
        return 'hm'
    if name.endswith('.nix'):
        return 'nd'
    return None


# ── nico-version header management ────────────────────────────────────────────

_VERSION_NOTYPE_RE = re.compile(
    r'^(# nico-version: )([0-9a-f]{8})', re.MULTILINE
)
_VERSION_ANY_RE = re.compile(
    r'^# nico-version: (?:[a-z]+#)?[0-9a-f]{8}(?:#[pr])?(?:#f\d+)?\n?', re.MULTILINE
)

# ── File format version ───────────────────────────────────────────────────────
# FILE_FORMAT and SUPPORTED_FORMATS live in brix.py – the layout they version is
# the section/brick marker format that module owns.

_FORMAT_RE = re.compile(
    r'^# nico-version: (?:[a-z]+#)?[0-9a-f]{8}(?:#[pr])?#f(\d+)', re.MULTILINE
)


def get_file_format(content: str) -> int:
    """Format version of a NiCo file; 1 when the marker is absent."""
    m = _FORMAT_RE.search(content)
    if not m:
        return 1
    try:
        return int(m.group(1))
    except ValueError:
        return 1


def set_file_format(content: str, version: int = FILE_FORMAT) -> str:
    """Set or replace the trailing #f<N> marker in the nico-version line."""
    if not re.search(r'^# nico-version: ', content, re.MULTILINE):
        return content
    return re.sub(
        r'^(# nico-version: (?:[a-z]+#)?[0-9a-f]{8}(?:#[pr])?)(?:#f\d+)?',
        rf'\g<1>#f{version}',
        content, count=1, flags=re.MULTILINE
    )

NICO_HEADER = (
    "# Generated by NiCo – NixOS Configurator\n"
    "# Do not edit manually. Use NiCo or add custom Nix via Nix-Brix.\n"
)


def get_nico_type(content: str) -> str | None:
    """Return the file-type code from the nico-version line, or None if absent.

    Returns:
      'co', 'nd', 'fl', etc.  – explicit type present
      ''                       – nico-version line exists but has no type
      None                     – no nico-version line at all (external file)
    """
    m = re.search(
        r'^# nico-version: (?:([a-z]+)#)?[0-9a-f]{8}', content, re.MULTILINE
    )
    if not m:
        return None
    return m.group(1) or ""


def insert_type(content: str, ftype: str) -> str:
    """Rewrite the nico-version line to prepend <ftype># before the hash."""
    return _VERSION_NOTYPE_RE.sub(rf'\g<1>{ftype}#\g<2>', content, count=1)


def get_panel_mode(content: str) -> str | None:
    """Return the panel mode flag from the nico-version line, or None if absent.

    Returns:
      'p'  – panel active
      'r'  – raw mode
      None – no flag set (use config default)
    """
    m = re.search(
        r'^# nico-version: (?:[a-z]+#)?[0-9a-f]{8}#([pr])', content, re.MULTILINE
    )
    return m.group(1) if m else None


def set_panel_mode(content: str, mode: str) -> str:
    """Set or replace the panel mode flag (#p or #r) in the nico-version line."""
    return re.sub(
        r'^(# nico-version: (?:[a-z]+#)?[0-9a-f]{8})(?:#[pr])?',
        rf'\g<1>#{mode}',
        content, count=1, flags=re.MULTILINE
    )


def file_in_raw_mode(path: Path) -> bool:
    """True if the file on disk carries the raw-mode flag (#r).

    Every panel write path asks this before regenerating a file. A file in
    raw mode belongs to the raw editor: a background form save regenerated it
    anyway, dropped the #r and replaced raw edits to form-known settings with
    stale form values; the next raw save then hit ERR_MANAGED_FILE
    (measured 2026-11-17). Skipping is reported as success, so rebuild and
    dry-run, which save the form first, still run.
    """
    try:
        return get_panel_mode(path.read_text(encoding="utf-8")) == "r"
    except OSError:
        return False


def check_brix_integrity(content: str) -> bool:
    """Return True if all brix/brick open/close markers are properly paired."""
    opens  = len(re.findall(r'^# <bri(?:x|ck):', content, re.MULTILINE))
    closes = len(re.findall(r'^# </bri(?:x|ck):', content, re.MULTILINE))
    return opens == closes


def set_type_in_content(content: str, ftype: str) -> str:
    """Replace or insert the type code in the nico-version line, recomputing the hash.

    Handles all three cases:
      - type already present  → remove old line, recompute hash, write new line
      - no type, has hash     → remove old line, recompute hash, write new line
      - no nico-version line  → prepend nico-version line (+ NiCo header for CO only)
    Panel mode flag (#p/#r) is preserved when rewriting an existing line.
    """
    if _VERSION_ANY_RE.search(content):
        panel_flag   = get_panel_mode(content)
        canonical    = _VERSION_ANY_RE.sub('', content, count=1)
        h            = generator.content_hash(canonical)
        panel_suffix = f'#{panel_flag}' if panel_flag else ''
        # The marker follows the markers in the body, not the old header: this
        # runs both after a regeneration (body is current) and on a file that
        # was only re-stamped (body stays as it was).  A higher number from a
        # newer NiCo wins – this version must not claim to have downgraded it.
        stored       = get_file_format(content)
        fmt          = stored if stored > FILE_FORMAT else detect_content_format(content)
        fmt_suffix   = f'#f{fmt}'
        new_line     = f"# nico-version: {ftype}#{h}{panel_suffix}{fmt_suffix}\n"
        return _VERSION_ANY_RE.sub(new_line, content, count=1)
    if ftype == 'co':
        canonical = NICO_HEADER + content
        h = generator.content_hash(canonical)
        nico_line = f"# nico-version: {ftype}#{h}#f{detect_content_format(content)}\n"
        return f"{NICO_HEADER}{nico_line}{content}"
    h = generator.content_hash(content)
    nico_line = f"# nico-version: {ftype}#{h}#f{detect_content_format(content)}\n"
    return f"{nico_line}{content}"


# ── Brick helpers ──────────────────────────────────────────────────────────────

def brick_body(text: str) -> str:
    """Extract body lines from a formatted brick text (strips start/end marker lines)."""
    lines = text.splitlines(keepends=True)
    if len(lines) >= 2:
        return "".join(lines[1:-1])
    return ""


def modify_brick_in_file(
    nixos_dir: str,
    fname: str,
    modifier,  # callable: dict[str, dict] -> dict[str, dict]
) -> tuple[bool, str, list[dict]]:
    """Read fname, apply modifier(blocks) → new_blocks, rewrite with updated hash.

    Returns (success, error_key_or_empty, details).  A write that *introduces* a
    nested brick is refused with ERR_BRICK_NESTED; a nesting that was already in
    the file is written through and returned as a hint instead.  Blocking on it
    would lock the user out of every brick action in that file – including the
    one they need to repair it.  A write that makes the file unreadable for Nix
    is refused the same way, with ERR_BRICK_BREAKS_FILE and the Nix message in
    `details`.
    """
    root  = Path(nixos_dir).resolve()
    fpath = (root / fname).resolve()
    try:
        fpath.relative_to(root)
    except ValueError:
        return False, "ERR_SYSTEM_PATH", []
    if not fpath.exists():
        return False, "ERR_FILE_NOT_FOUND", []
    try:
        content = fpath.read_text(encoding="utf-8")
    except OSError:
        return False, "ERR_READ", []

    ftype = get_nico_type(content)
    if ftype is None or ftype == "":
        ftype = "nd"

    # Brick actions take the file apart and put it together again around the
    # section markers. A file NiCo cannot represent has none of them where
    # they are expected; it is edited as text.
    if file_unmappable(nixos_dir, fname, content, ftype):
        return False, "ERR_NOT_MAPPABLE", []

    if ftype == "hm":
        try:
            content, blocks = normalize_hm_content(content)
        except Exception:
            blocks = extract_brick_blocks(content)
    else:
        blocks = extract_brick_blocks(content)
    # Modifiers change the dict in place; keep the state before for the diff.
    old_blocks = {k: dict(v) for k, v in blocks.items()}
    new_blocks = modifier(blocks)
    clean      = strip_brick_blocks(content)
    if ftype == "fl":
        # The outputs argument list is derived from the INPX bricks, but only
        # the generator wrote it – a brick write left it stale.
        clean = sync_outputs_args(clean, old_blocks, new_blocks)
    with_brick = inject_brick_blocks(clean, new_blocks)
    final      = set_type_in_content(with_brick, ftype)

    introduced = new_nested_bricks(content, final)
    if introduced:
        return False, "ERR_BRICK_NESTED", introduced

    # A brick is free Nix, and free Nix can be wrong. Until now the only check
    # was bracket balance, which a bare word passes: `nixpkgs-unstable` alone
    # in a brick made flake.nix unreadable, was saved without a word, and the
    # config stayed unbuildable for a day before anyone noticed (Martins
    # config, 2026-10-30). Refused the same way as a nesting – only when this
    # write is what breaks it, so a file that is already broken can still be
    # repaired through the same dialogs.
    from . import validator as _val
    broke = _val.breaks_parsing(content, final)
    if broke:
        used = input_still_used(broke, final, old_blocks, new_blocks)
        info = {"input": used[0], "brick": used[1]} if used else {}
        return False, "ERR_BRICK_BREAKS_FILE", [{"file": fname, "detail": broke, **info}]

    try:
        atomic.write_text(fpath, final)
    except OSError:
        return False, "ERR_WRITE", []

    return True, "", find_nested_bricks(final)


# ── Home Manager patching ──────────────────────────────────────────────────────

def hm_patch_str(content: str, key: str, value: str) -> str:
    ek = re.escape(key)
    # Lambda replacement: value must not be interpreted as re.sub template
    # (backslashes/\g would break); nix_esc keeps the .nix string valid.
    quoted = f'"{generator.nix_esc(value)}"'
    # The old value may contain an escaped quote: `"[^"]*"` stopped there and
    # left the rest behind the new string (revision 2026-11-18, finding 19).
    return re.sub(rf'({ek}\s*=\s*)"(?:[^"\\]|\\.)*"', lambda m: m.group(1) + quoted, content)


def hm_patch_bool(content: str, key: str, value: bool) -> str:
    ek = re.escape(key)
    nv = "true" if value else "false"
    return re.sub(rf'({ek}\s*=\s*)(true|false)', rf'\g<1>{nv}', content)


def hm_patch_args(content: str, args: list) -> str:
    # Dedup by base name (first occurrence wins) – duplicate formal args
    # are a Nix syntax error ("duplicate formal function argument").
    cleaned: list[str] = []
    seen: set[str] = set()
    for a in args:
        a = (a or "").strip()
        base = hm_generator._hm_arg_base(a)
        if not a or not base or base in seen:
            continue
        seen.add(base)
        cleaned.append(a)
    all_args = cleaned + ["..."]
    new_header = "{ " + ", ".join(all_args) + " }:"
    return re.sub(r'^\s*\{[^}]*\}\s*:', new_header, content, count=1,
                  flags=re.MULTILINE | re.DOTALL)


def hm_patch_init_extra(content: str, new_extra: str) -> str:
    for shell, key in [("bash", "initExtra"), ("zsh", "initExtra"), ("fish", "shellInit")]:
        if not re.search(rf'programs\.{shell}\s*=\s*\{{', content):
            continue
        ek = re.escape(key)
        if new_extra:
            indented = "\n".join(f"      {ln}" for ln in new_extra.splitlines())
            def _repl(_m, _k=key, _ind=indented):
                return f"\n    {_k} = ''\n{_ind}\n    '';"
            patched, n = re.subn(
                rf'\s*{ek}\s*=\s*\'\'[\s\S]*?\'\'[ \t]*;',
                _repl, content, count=1
            )
            if n > 0:
                return patched
            def _ins(_m, _k=key, _ind=indented):
                body = _m.group(0)
                close = body.rfind("};")
                return body[:close] + f"    {_k} = ''\n{_ind}\n    '';\n  }};"
            return re.sub(
                rf'programs\.{shell}\s*=\s*\{{[\s\S]*?\n  \}};',
                _ins, content, count=1
            )
        else:
            return re.sub(
                rf'\s*{ek}\s*=\s*\'\'[\s\S]*?\'\'[ \t]*;',
                '', content, count=1
            )
    return content


def hm_patch_packages(content: str, packages: list) -> str:
    pkg_re = re.compile(
        r'(\s*)home\.packages\s*=(?:\s*with\s+pkgs\s*;)?\s*\[[\s\S]*?\]\s*;'
    )
    m = pkg_re.search(content)
    if m:
        indent = m.group(1).replace('\n', '')
        if packages:
            pkg_lines = "\n".join(f"{indent}  pkgs.{p}" for p in packages)
            new_block = f"{indent}home.packages = [\n{pkg_lines}\n{indent}];"
            return content[:m.start()] + "\n" + new_block + content[m.end():]
        return content[:m.start()] + content[m.end():]
    if packages:
        indent = "  "
        pkg_lines = "\n".join(f"{indent}  pkgs.{p}" for p in packages)
        new_block = f"\n{indent}home.packages = [\n{pkg_lines}\n{indent}];"
        return re.sub(r'(\n\}\n)', rf'{new_block}\1', content, count=1)
    return content


def hm_update_hash(content: str) -> str:
    """Recompute the hash in the nico-version line, leaving the rest of it.

    Uses the generator's pattern. The one that stood here did not know the
    `#f<N>` suffix: the version line stayed in the hashed text and the file
    read as "modified" right after NiCo wrote it (revision 2026-11-10, B44).
    """
    m = generator._VERSION_RE.search(content)
    if not m:
        return content
    canonical = generator._VERSION_RE.sub('', content, count=1)
    new_hash = generator.content_hash(canonical)
    return content[:m.start(1)] + new_hash + content[m.end(1):]


def normalize_hm_content(content: str) -> tuple[str, dict]:
    """Return normalized HM content plus extracted/derived brick blocks.

    A file NiCo cannot represent (importer.config_unmappable) comes back
    untouched – `let … in` is the usual way to write a Home Manager file, and
    regenerating it would drop the bindings the body refers to.
    """
    existing_bricks = extract_brick_blocks(content)
    if importer.config_unmappable(content):
        return content, existing_bricks
    clean_content   = strip_brick_blocks(content)
    hm              = importer.parse_home_config(clean_content)
    blocks          = dict(existing_bricks)
    rest            = importer.build_home_rest_brix(clean_content, hm)
    if rest.strip():
        rest_blocks = brix_content_to_bricks(rest, section="TAIL", existing_blocks=blocks)
        blocks.update(rest_blocks)
    # Comments outside bricks (importer.collect_notes); after
    # build_home_rest_brix, which may switch the shell block to a brick.
    blocks = _merge_notes(
        blocks, importer.collect_notes(content, rest_comments=False),
        render=lambda b: hm_generator.generate_home_nix({**hm, "hm_brick_blocks": b}))
    hm_data                  = dict(hm)
    hm_data["hm_brick_blocks"] = blocks
    # Gegenprobe (2026-11-19, phase 3): a field that would change or add to
    # what the file says is not taken, its lines stay bricks. Without it a
    # `programs.zsh = { enable = false; }` came back switched on (revision
    # 2026-11-18, finding 11). If it cannot be settled, the file stays as is.
    try:
        hm_data = fidelity.settle(content, hm_data, hm_generator.generate_home_nix,
                                  bricks_key="hm_brick_blocks",
                                  section=hm_generator.HM_SECTION_END)
    except fidelity.NotFaithful:
        return content, existing_bricks
    return hm_generator.generate_home_nix(hm_data), hm_data["hm_brick_blocks"]


# ── Files NiCo cannot represent ────────────────────────────────────────────────

def flake_is_managed(content: str) -> bool:
    """True when NiCo may regenerate this flake.nix.

    Two conditions, and until revision 2026-11-10 only the first was asked:
    the file carries a nico stamp, and its content has the shape the generator
    produces. The stamp alone says little – every file gets one the first time
    it is opened in the interface.
    """
    return get_nico_type(content) is not None and \
        importer.flake_unmappable(content) is None


def file_unmappable(nixos_dir: str, rel_path: str, content: str,
                    ftype: "str | None" = None) -> bool:
    """True when the file at rel_path is one NiCo would regenerate, and cannot.

    Covers the files with a form behind them: the root flake.nix, the root
    configuration.nix, host files, Home Manager files and anything typed 'co'
    or 'hm'. Every other file is raw anyway.
    """
    parts = Path(rel_path).parts
    if not parts:
        return False
    settings = config_manager.load_config_settings(nixos_dir)
    hosts_dir = (settings.get("hosts_dir") or "hosts").strip() or "hosts"
    hm_dir = (settings.get("hm_dir") or "home").strip() or "home"

    if rel_path == "flake.nix":
        return importer.flake_unmappable(content) is not None
    if ftype == "fl":
        return False        # a flake.nix elsewhere is never regenerated
    is_module = (
        rel_path == "configuration.nix"
        or ftype in ("co", "hm")
        or (len(parts) == 3 and parts[0] == hosts_dir and parts[2] == "default.nix")
        or (len(parts) >= 2 and parts[0] == hm_dir)
    )
    return is_module and importer.config_unmappable(content)


def unmappable_files(nixos_dir: str) -> list[str]:
    """The root files with a form behind them that NiCo has to leave alone."""
    found: list[str] = []
    for rel in ("configuration.nix", "flake.nix"):
        path = Path(nixos_dir) / rel
        try:
            if path.is_file() and file_unmappable(
                    nixos_dir, rel, path.read_text(encoding="utf-8")):
                found.append(rel)
        except OSError:
            pass
    return found


def flake_mode(nixos_dir: str) -> bool:
    """True when this config is built as a flake – see config_manager.flake_mode."""
    return config_manager.flake_mode(nixos_dir)


def reimport_flake(nixos_dir: str, data: dict) -> bool:
    """Take over an imported flake.nix: merge its fields, regenerate it.

    Returns False and leaves the file exactly as it is when NiCo cannot
    represent it (importer.flake_unmappable). It then carries no "Generated
    by NiCo" line and is edited in the raw editor.

    Neither sets the `flakes` field nor writes configuration.nix (revision
    2026-11-10, B34 and the rest of B39). The field used to be forced on
    because it decided the build path; that is flake_mode() now, and the
    field is only the experimental-features line – which an imported config
    either has or does not have. The save_config() calls existed to store
    that field and created a configuration.nix from defaults next to a
    flake that has none; the flake_* fields live in flake.nix.
    """
    flake_path = Path(nixos_dir) / "flake.nix"
    if not flake_path.exists():
        return False
    data["_flake_mode"] = True
    try:
        flake_content = flake_path.read_text(encoding="utf-8")
        if importer.flake_unmappable(flake_content) is not None:
            return False
        flake_fields  = importer.parse_flake_nix(flake_content)
        flake_brix    = importer.flake_brix_for(flake_content)
        flake_brix    = importer.ensure_flake_host_bricks(flake_content, flake_brix)
        data.update(flake_fields)
        data["flake_brick_blocks"] = flake_brix
        text = generator.generate_flake_nix(data, nixos_dir=nixos_dir)
        try:
            # Gegenprobe (2026-11-19): what NiCo would write must say what
            # the file says; otherwise the flake stays as it came.
            fidelity.require_faithful(flake_content, text)
        except fidelity.NotFaithful:
            return False
        atomic.write_text(flake_path, text)
        return True
    except OSError:
        return False


# ── Flake host management ──────────────────────────────────────────────────────

def scan_flake_hosts(flake_path: Path) -> list[str]:
    """Scan an external flake.nix for nixosConfigurations host names."""
    try:
        content = flake_path.read_text(encoding="utf-8")
    except OSError:
        return []
    found: list[str] = []
    for m in re.finditer(r'nixosConfigurations\s*\.\s*"?([\w-]+)"?', content):
        h = m.group(1)
        if h not in found:
            found.append(h)
    return found


# Host names in a flake.nix NiCo cannot represent. A text search, decided
# 2026-11-13 over `nix eval .#nixosConfigurations --apply builtins.attrNames`:
# that is exact but takes seconds, may need the network, and the host list is
# asked for on every rebuild click. The price is that computed hosts
# (`nixosConfigurations = import ./hosts inputs;`, a mkHost helper) are not
# seen; get_flake_hosts then falls back to the hostname.
_RE_HOST_ATTRPATH = re.compile(r'nixosConfigurations\s*\.\s*"?([\w-]+)"?\s*=')
_RE_HOST_ASSIGN   = re.compile(
    r'(?<![\w.-])"?([A-Za-z_][\w-]*)"?\s*=\s*(?:[\w-]+\.)*nixosSystem\b')


def scan_unmapped_flake_hosts(content: str) -> list[str]:
    """Host names found by text search, in the order they appear."""
    hits = [(m.start(), m.group(1))
            for rx in (_RE_HOST_ATTRPATH, _RE_HOST_ASSIGN)
            for m in rx.finditer(content)]
    found: list[str] = []
    for _, name in sorted(hits):
        if name not in found:
            found.append(name)
    return found


def get_flake_hosts(nixos_dir: str, data: dict) -> list[str]:
    """Return all flake host names for rebuild/dry-run, sourced from flake.nix on disk."""
    hosts: list[str] = []
    flake_path = Path(nixos_dir) / "flake.nix"

    if flake_path.exists():
        try:
            flake_data = dict(data)
            flake_data.update(importer.parse_flake_nix(flake_path.read_text(encoding="utf-8")))
            for h in flake_data.get("flake_hosts") or []:
                name = h.get("name", "")
                if name and name not in hosts:
                    hosts.append(name)
            flake_text = flake_path.read_text(encoding="utf-8")
            if importer.flake_unmappable(flake_text) is not None:
                for name in scan_unmapped_flake_hosts(flake_text):
                    if name not in hosts:
                        hosts.append(name)
        except OSError:
            pass

    for h in data.get("flake_hosts") or []:
        name = h.get("name", "")
        if name and name not in hosts:
            hosts.append(name)

    if flake_path.exists():
        try:
            brix = extract_brick_blocks(flake_path.read_text(encoding="utf-8"))
            for bname, block in brix.items():
                if block.get("section") == "OUTH" and bname not in hosts:
                    hosts.append(bname)
                elif bname == "outputs-declaration" and block.get("section") == "Outputs":
                    body = brick_body(block["text"])
                    for m in re.finditer(r'\b([\w-]+)\s*=\s*nixpkgs\.lib\.nixosSystem', body):
                        h = m.group(1)
                        if h not in hosts:
                            hosts.append(h)
        except OSError:
            pass

    if not hosts:
        single = (data.get("hostname") or "nixos").strip()
        if single:
            hosts.append(single)

    return hosts or ["nixos"]


def flake_outputs_modify_host(brix_text: str, action: str, host_name: str) -> str | None:
    """Add or remove a nixosSystem host entry inside the nixosConfigurations block
    of an outputs-declaration Brix body. Returns the modified body or None."""
    body = brick_body(brix_text)

    m = re.search(r'\bnixosConfigurations\s*=\s*\{', body)
    if not m:
        return None
    brace_start = body.index('{', m.start())
    depth, i, cfg_end = 0, brace_start, len(body)
    while i < len(body):
        if body[i] == '{':
            depth += 1
        elif body[i] == '}':
            depth -= 1
            if depth == 0:
                cfg_end = i
                break
        i += 1

    cfg_body = body[brace_start + 1:cfg_end]

    def _extract_system_block(text: str, sys_match) -> tuple[int, int]:
        bp = text.index('{', sys_match.end() - 1)
        d, j, end = 0, bp, len(text)
        while j < len(text):
            if text[j] == '{':
                d += 1
            elif text[j] == '}':
                d -= 1
                if d == 0:
                    end = j + 1
                    while end < len(text) and text[end] in ' \t':
                        end += 1
                    if end < len(text) and text[end] == ';':
                        end += 1
                    break
            j += 1
        return sys_match.start(), end

    if action == 'add':
        sys_m = re.search(
            r'\s+[\w-]+\s*=\s*nixpkgs\.lib\.nixosSystem\s*\{', cfg_body
        )
        if not sys_m:
            return None
        src_name = re.search(r'([\w-]+)\s*=\s*nixpkgs', sys_m.group()).group(1)
        start_pos, end_pos = _extract_system_block(cfg_body, sys_m)
        template_block = cfg_body[start_pos:end_pos]
        new_block = (
            template_block
            .replace(f'{src_name} =', f'{host_name} =', 1)
            .replace(f'./hosts/{src_name}/', f'./hosts/{host_name}/')
            .replace(f'./hosts/{src_name}', f'./hosts/{host_name}')
        )
        new_cfg_body = cfg_body.rstrip('\n') + '\n' + new_block + '\n'

    elif action == 'remove':
        sys_m = re.search(
            r'\s+' + re.escape(host_name) + r'\s*=\s*nixpkgs\.lib\.nixosSystem\s*\{',
            cfg_body,
        )
        if not sys_m:
            return None
        start_pos, end_pos = _extract_system_block(cfg_body, sys_m)
        new_cfg_body = cfg_body[:start_pos] + cfg_body[end_pos:]
    else:
        return None

    return body[:brace_start + 1] + new_cfg_body + body[cfg_end:]


