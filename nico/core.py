def _merge_notes(blocks: dict, notes: list, render=None) -> dict:
    """Add rescued comments to the file's NOTES_BRICK (importer.collect_notes).

    render(blocks) -> file text, when given, drops every block whose lines
    all reappear in the file NiCo writes anyway: a form value kept verbatim
    (a user's package list, say) carries its comments along, and they must
    not stand twice. Appends to an existing NOTES_BRICK; a block already
    standing in any brick is not added again.
    """
    if not notes:
        return blocks
    if render is not None:
        out = {l.strip() for l in render(blocks).splitlines()}
        notes = [n for n in notes
                 if not all(("#" + l).strip() in out or ("# " + l).strip() in out
                            or not l.strip() for l in n.lines)]
    bodies = "\n".join(brick_body(b.get("text", "")) for b in blocks.values())
    fresh = [n for n in notes if importer.render_notes([n]) not in bodies]
    if not fresh:
        return blocks
    blocks = dict(blocks)
    add = importer.render_notes(fresh)
    name = importer.NOTES_BRICK
    old = blocks.get(name)
    if old is not None:
        body = brick_body(old["text"]).rstrip("\n")
        body = f"{body}\n{importer.NOTES_SEPARATOR}\n{add}" if body.strip() else add
        blocks[name] = {**old, "text": format_brick(old["section"], old["order"], name, body)}
    else:
        order = next_order_for_section(blocks, "TAIL")
        blocks[name] = {"section": "TAIL", "order": order,
                        "text": format_brick("TAIL", order, name, add)}
    return blocks


def keep_unmodelled(disk_text: str, bricks: dict | None, render=None) -> dict:
    """Bricks for a regenerated file, plus whatever on disk the form cannot hold.

    Every panel write regenerates the file from the form and the bricks it
    already has. A statement outside any brick that the form does not model
    fell out on that write. Two ways got it there unnoticed: a raw-mode save
    re-stamps the hash (routes/files.py), so a switch back to the panel never
    reached the rescue in load_and_normalize_config; and host files had no
    rescue at all, so even an edit from outside was lost (measured
    2026-11-16, manifest „Befund aus Schritt 0“).

    Only build_rest_brix, i.e. what the form cannot represent. Not
    importer.rescue_into_bricks: that compares against the form values, and
    a value the user cleared in the form would come back as a brick.

    NiCo's own output yields nothing here (measured on the 18 roundtrip
    configs and the defaults, tree-sitter and regex path), so repeated saves
    do not add bricks. A statement already standing in one of the given
    bricks is skipped: the import (server._apply_import_result) has turned
    the same rest into bricks of the same names just before it saves, and
    they must not appear twice. A name already taken by other content gets a
    numbered suffix instead of replacing the existing brick.
    """
    blocks = dict(bricks or {})
    if not disk_text or importer.config_unmappable(disk_text):
        return blocks
    blocks = _keep_rest(disk_text, blocks)
    # Comments outside any brick (importer.collect_notes); `render` lets
    # _merge_notes skip what the regenerated file carries along anyway.
    return _merge_notes(blocks, importer.collect_notes(disk_text), render)


def _keep_rest(disk_text: str, blocks: dict) -> dict:
    """The statement part of keep_unmodelled."""
    rest = importer.build_rest_brix(strip_brick_blocks(disk_text), {})
    if not rest.strip():
        return blocks
    bodies = [brick_body(b.get("text", "")) for b in blocks.values()]
    for name, block in brix_content_to_bricks(rest, section="HEAD",
                                              existing_blocks=blocks).items():
        stmt = brick_body(block["text"]).strip()
        if stmt and any(stmt in body for body in bodies):
            continue
        final, n = name, 2
        while final in blocks:
            final = f"{name}-{n}"
            n += 1
        if final != name:
            block = {**block, "text": format_brick(block["section"], block["order"],
                                                   final, brick_body(block["text"]))}
        blocks[final] = block
    return blocks


# ── Changed outside NiCo (Fall A, decision Martin 2026-11-18) ─────────────────
# Every file NiCo writes from a form carries a hash. A wrong or missing hash
# means NiCo did not write what is on disk now, and the next form save would
# restructure the file: settings the form does not know become Nix-Bricks,
# comments go to imported-notes. That used to happen without a word - for
# configuration.nix and flake.nix already on a GET, for host and Home Manager
# files on the next save, and their hash was never even looked at. Now the
# interface asks first: restructure (checkpoint before), open as raw, or show
# what would change.

def _host_of(nixos_dir: str, rel: str) -> "str | None":
    """Host name if rel is <hosts_dir>/<host>/default.nix, else None."""
    cfg = config_manager.load_config_settings(nixos_dir)
    hosts = (cfg.get("hosts_dir") or "hosts").strip() or "hosts"
    parts = Path(rel).parts
    if len(parts) == 3 and parts[0] == hosts and parts[2] == "default.nix":
        return parts[1]
    return None


def _is_hm_file(nixos_dir: str, rel: str, content: str) -> bool:
    cfg = config_manager.load_config_settings(nixos_dir)
    hm_dir = (cfg.get("hm_dir") or "home").strip() or "home"
    parts = Path(rel).parts
    return (len(parts) >= 2 and parts[0] == hm_dir) or get_nico_type(content) == "hm"


def _panel_file(nixos_dir: str, rel: str, content: str) -> bool:
    """A file a form writes back and NiCo can represent: configuration.nix,
    a NiCo flake.nix, host default.nix, Home Manager files."""
    rel = (rel or "").strip()
    if rel not in ("configuration.nix", "flake.nix") and \
            not _host_of(nixos_dir, rel) and not _is_hm_file(nixos_dir, rel, content):
        return False
    # A flake.nix without a nico stamp is not NiCo's (flake_is_managed).
    if rel == "flake.nix" and not flake_is_managed(content):
        return False
    return not file_unmappable(nixos_dir, rel, content)


def outside_status(nixos_dir: str, rel: str, content: str) -> "str | None":
    """'modified' or 'no_hash' when the hash says NiCo did not write this
    state; None otherwise. In raw mode as well: there it is only a notice
    (Martin, 2026-11-18)."""
    if not _panel_file(nixos_dir, rel, content):
        return None
    status = generator.check_version_hash(content)
    return None if status == "ok" else status


_MARKER_SECTION_RE = re.compile(r'^(\s*# <brick: )([^/>]+?)( / .*)$')


def _body_lines(text: str) -> list:
    """Lines to compare: without the version line, legacy section names in
    brick markers read as their code (brix.LEGACY_SECTIONS) – the import
    wrote `Start` for HEAD until 2026-11-18, and the generator writes the
    code, so every imported file would otherwise count as changed."""
    from .brix import LEGACY_SECTIONS
    out = []
    for line in text.splitlines():
        if line.startswith("# nico-version:"):
            continue
        m = _MARKER_SECTION_RE.match(line)
        if m and m.group(2) in LEGACY_SECTIONS:
            line = m.group(1) + LEGACY_SECTIONS[m.group(2)] + m.group(3)
        out.append(line)
    return out


def panel_changes(nixos_dir: str, rel: str, content: str) -> bool:
    """True when the panel would write this file differently from how it is.

    Asked when switching from raw mode to the panel (Martin, 2026-11-18).
    The hash cannot answer it there: raw save and the panel switch recompute
    it, so an edit in the raw editor looked like NiCo's own, and whatever
    the panel could not place was dropped without a word – a stray `.` in
    Martin's VM run. Opening a file asks the hash instead (outside_status):
    edits in the raw editor only reach the panel through the switch, and
    comparing on every opening would also ask about files an older NiCo
    wrote in its older layout. The version line does not count.
    """
    if not _panel_file(nixos_dir, rel, content):
        return False
    rel = (rel or "").strip()
    if rel not in ("configuration.nix", "flake.nix") and not _host_of(nixos_dir, rel):
        # Home Manager: the panel patches single lines in place (/api/hm/patch)
        # and never regenerates the file, so "what would it write" has no
        # answer. The hash decides there, as before; HM in raw mode is the
        # next pass anyway (manifest, 2026-11-18).
        return outside_status(nixos_dir, rel, content) is not None
    try:
        after = restructured_text(nixos_dir, rel, content)
    except fidelity.NotFaithful:
        # The panel would change what the file says: ask, never switch
        # silently. Restructuring then refuses (ERR_NOT_MAPPABLE).
        return True
    except Exception:
        # The panel save would fail the same way and say so; nothing to ask.
        return False
    return _body_lines(after) != _body_lines(content)


def restructure_unfaithful(nixos_dir: str, rel: str, content: str) -> bool:
    """True when NiCo cannot write this file back without changing what it
    says (fidelity.settle). Such a file stays in raw mode, like an
    unmappable one: switching to the panel would hand the form values the
    file does not hold."""
    try:
        restructured_text(nixos_dir, rel, content)
    except fidelity.NotFaithful:
        return True
    except Exception:
        return False
    return False


def _restructure_co(nixos_dir: str, nix_content: str, data: dict) -> str:
    """The text a panel save would make of this configuration.nix; fills data."""
    existing_bricks = extract_brick_blocks(nix_content)
    nix_without_bricks = strip_brick_blocks(nix_content)
    recognized = importer.parse_config(nix_without_bricks)
    data.update(recognized)
    rest = importer.build_rest_brix(nix_without_bricks, recognized)
    blocks = dict(existing_bricks)
    if rest.strip():
        blocks.update(brix_content_to_bricks(rest, section="HEAD", existing_blocks=blocks))
    data["_flake_mode"] = flake_mode(nixos_dir)
    data["brick_blocks"] = _merge_notes(
        blocks, importer.collect_notes(nix_content),
        render=lambda b: generator.generate_configuration_nix({**data, "brick_blocks": b}))
    # Gegenprobe (2026-11-19): fields that would change or add to what the
    # file says are not taken; their lines stay bricks. NotFaithful goes up.
    data.update(fidelity.settle(nix_content, data, generator.generate_configuration_nix))
    return generator.generate_configuration_nix(data)


def _restructure_host(nixos_dir: str, host: str) -> str:
    """The text a panel save would make of this host's default.nix."""
    host_data = config_manager.load_host_config(nixos_dir, host) or {}
    cfg = config_manager.load_config_settings(nixos_dir)
    host_dir = Path(nixos_dir) / ((cfg.get("hosts_dir") or "hosts").strip() or "hosts") / host
    host_nix = host_dir / "default.nix"
    hw_config = (host_dir / "hardware-configuration.nix").exists()
    disk = host_nix.read_text(encoding="utf-8")
    bricks = dict(host_data.get("brick_blocks", {}))
    bricks.update(extract_brick_blocks(disk))
    host_data["brick_blocks"] = keep_unmodelled(
        disk, bricks,
        render=lambda b: generator.generate_host_nix({**host_data, "brick_blocks": b}, host, hw_config))
    host_data = fidelity.settle(
        disk, host_data, lambda d: generator.generate_host_nix(d, host, hw_config))
    return generator.generate_host_nix(host_data, host, hw_config)


def restructured_text(nixos_dir: str, rel: str, content: str) -> str:
    """What NiCo would write for this file when it restructures it."""
    rel = (rel or "").strip()
    if rel == "configuration.nix":
        data = config_manager.load_config(nixos_dir) or config_manager.get_defaults()
        return _restructure_co(nixos_dir, content, data)
    if rel == "flake.nix":
        data = config_manager.load_config(nixos_dir) or config_manager.get_defaults()
        data.update(importer.parse_flake_nix(content))
        # A flake NiCo generated keeps its bricks as they are, like the flake
        # panel save (/api/config/flake); build_flake_brix is for a foreign
        # one and doubled the host bricks of a generated flake.
        brix = extract_brick_blocks(content) if "# Generated by NiCo" in content \
            else importer.build_flake_brix(content)
        data["flake_brick_blocks"] = importer.ensure_flake_host_bricks(content, brix)
        text = generator.generate_flake_nix(data, nixos_dir=nixos_dir)
        fidelity.require_faithful(content, text)      # NotFaithful goes up
        return text
    host = _host_of(nixos_dir, rel)
    if host:
        return _restructure_host(nixos_dir, host)
    if _is_hm_file(nixos_dir, rel, content):
        return normalize_hm_content(content)[0]
    raise ValueError("ERR_NOT_RESTRUCTURABLE")


def restructure_file(nixos_dir: str, rel: str) -> str:
    """Restructure the file on disk; returns the new text. No checkpoint
    here - the caller makes it first, with the state from outside."""
    target = _resolve_config_rel(Path(nixos_dir).resolve(), rel)
    text = restructured_text(nixos_dir, rel, target.read_text(encoding="utf-8"))
    if _host_of(nixos_dir, rel):
        duplicates = validator.duplicate_attrs_in(text)
        if duplicates:
            raise config_manager.DuplicateAttrError(duplicates)
    atomic.write_text(target, text)
    return text


def load_and_normalize_config(nixos_dir: str) -> dict:
    """
    Load config state from disk, normalize any externally-modified .nix files,
    and return the complete data dict (same shape as /api/config GET response).
    """
    data = config_manager.load_config(nixos_dir)

    cfg_nix = Path(nixos_dir) / "configuration.nix"
    if cfg_nix.exists():
        try:
            nix_content = cfg_nix.read_text(encoding="utf-8")
            hash_status = generator.check_version_hash(nix_content)
            if data is None:
                data = config_manager.get_defaults()
            if importer.config_unmappable(nix_content):
                # Not parsed, not rewritten: the model keeps its defaults and
                # the file stays byte for byte (revision 2026-11-10, B33).
                data["brick_blocks"] = extract_brick_blocks(nix_content)
            elif hash_status in ("modified", "no_hash") and \
                    get_panel_mode(nix_content) != "r":
                # Read as it would be restructured, but not written: the
                # user decides first (restructure_file, Fall A 2026-11-18).
                # Until then this rewrote the file on every GET, silently.
                _restructure_co(nixos_dir, nix_content, data)
            else:
                data["brick_blocks"] = extract_brick_blocks(nix_content)
        except OSError:
            pass

    if data is None:
        config_manager.init_nico_dir(nixos_dir)
        data = config_manager.load_config(nixos_dir)

    config_manager.migrate_nico_json(nixos_dir)

    flake_nix_path = Path(nixos_dir) / "flake.nix"
    if flake_nix_path.exists():
        try:
            flake_content = flake_nix_path.read_text(encoding="utf-8")
            parsed = importer.parse_flake_nix(flake_content)
            data.update(parsed)
            # No save_config() here: the flake_* fields live in flake.nix, not
            # in configuration.nix, so there is nothing to persist - and the
            # call created a configuration.nix from defaults next to a flake
            # that has none (revision 2026-11-10, B39).
            # Not rewritten here any more either (Fall A, 2026-11-18): an
            # externally changed flake.nix waits for the user's answer.
            flake_brix = extract_brick_blocks(flake_content)
            data["flake_brick_blocks"] = importer.ensure_flake_host_bricks(flake_content, flake_brix)
        except OSError:
            pass

    # Legacy root home.nix (pre HM-refactor): read-only. Bricks are still
    # exposed for display, but the file is never normalized or rewritten –
    # HM files live in hm_dir/<username>.nix; the validator (hm_orphan_root)
    # reports a leftover root home.nix.
    home_nix_path = Path(nixos_dir) / "home.nix"
    if home_nix_path.exists():
        try:
            data["hm_brick_blocks"] = extract_brick_blocks(
                home_nix_path.read_text(encoding="utf-8")
            )
        except OSError:
            pass

    data["_unmappable"] = unmappable_files(nixos_dir)
    return data


def write_config_files(
    nixos_dir: str,
    data: dict,
    *,
    commit: bool = True,
    label: str = "",
) -> dict:
    """
    Write generated .nix files to nixos_dir.
    Returns {"success": True, "written": [...]} plus optional push fields.
    """
    nixos_path = Path(nixos_dir)
    conf_file = nixos_path / "configuration.nix"
    # The form does not send it, and must not be able to: see flake_mode().
    data["_flake_mode"] = flake_mode(nixos_dir)

    if conf_file.exists():
        conf_text = conf_file.read_text(encoding="utf-8")
        if importer.config_unmappable(conf_text):
            # Nothing is written, flake.nix included: the form model was never
            # filled from this file, so everything in it is a default.
            return {
                "success": False,
                "error":   "ERR_NOT_MAPPABLE",
                "file":    "configuration.nix",
            }
        data["brick_blocks"] = keep_unmodelled(
            conf_text, extract_brick_blocks(conf_text),
            render=lambda b: generator.generate_configuration_nix({**data, "brick_blocks": b}))

    # A file in raw mode is left alone (file_in_raw_mode); flake.nix below
    # is decided on its own.
    conf_raw = file_in_raw_mode(conf_file)

    # Refuse to write a file Nix would reject. The same leaf defined twice –
    # typically a brick carrying an attribute the form writes as well – stops
    # the build with "attribute … already defined". Writing it anyway would
    # leave the config unbuildable, so this is the one place that blocks
    # (unlike nested bricks below, which a form cannot fix).
    generated = None if conf_raw else generator.generate_configuration_nix(data)
    duplicates = importer.duplicate_leaf_paths(generated) if generated else []
    if duplicates:
        return {
            "success":    False,
            "error":      "ERR_DUPLICATE_ATTR",
            "duplicates": duplicates[:10],
        }

    flake_file, flake_text = None, None
    # An existing flake.nix is carried along; none is ever created here. That
    # is its own step (POST /api/flake/create), because a flake.nix needs a
    # host directory and the hardware config in it – writing only the file
    # left a config that could not be built (revision 2026-11-10, B34).
    if data["_flake_mode"]:
        flake_file = nixos_path / "flake.nix"
        _flake_content = flake_file.read_text(encoding="utf-8")
        if flake_is_managed(_flake_content) and get_panel_mode(_flake_content) != "r":
            data.update(importer.parse_flake_nix(_flake_content))
            flake_brix = extract_brick_blocks(_flake_content)
            flake_brix = importer.ensure_flake_host_bricks(_flake_content, flake_brix)
            if flake_brix:
                data["flake_brick_blocks"] = flake_brix
            flake_text = generator.generate_flake_nix(data, nixos_dir=str(nixos_path))
            # Carried along only when NiCo wrote the current state (hash) and
            # the new text says the same. The form of configuration.nix
            # changes nothing in flake.nix; rewriting it anyway dropped what
            # had been added from outside, without a question (revision
            # 2026-11-18, finding 3). Otherwise it stays, and opening it asks
            # (Fall A).
            if outside_status(str(nixos_path), "flake.nix", _flake_content) is not None:
                flake_text = None
            else:
                try:
                    fidelity.require_faithful(_flake_content, flake_text)
                except fidelity.NotFaithful:
                    flake_text = None
            # Checked before anything is written: one new file next to one old
            # one would be worse than either.
            duplicates = validator.duplicate_attrs_in(flake_text) if flake_text else []
            if duplicates:
                return {
                    "success":    False,
                    "error":      "ERR_DUPLICATE_ATTR",
                    "duplicates": duplicates,
                }

    written = []
    if generated is not None:
        atomic.write_text(conf_file, generated)
        written.append("configuration.nix")
    if flake_text is not None:
        atomic.write_text(flake_file, flake_text)
        written.append("flake.nix")

    # Root home.nix is legacy (pre HM-refactor) and never written anymore;
    # HM files are managed separately in hm_dir/<username>.nix.

    skipped_large: list[str] = []
    if commit:
        try:
            _, _, skipped_large = git_manager.auto_commit(nixos_dir, label=label)
        except Exception:
            pass

    result: dict = {"success": True, "written": written}
    # Never blocking here: the form write carries existing bricks along and the
    # user has no way to fix a nesting from a form – it would just refuse to save.
    nested: list[dict] = []
    for fname in written:
        try:
            text = (nixos_path / fname).read_text(encoding="utf-8")
        except OSError:
            continue
        for f in find_nested_bricks(text):
            nested.append({**f, "file": fname})
    if nested:
        result["nested"] = nested
    if skipped_large:
        # See write_raw_config_file: an oversized file that silently stays out
        # of the commit is exactly how the 2.1 GB log incident stayed unnoticed.
        result["skipped_large"] = skipped_large
    result.update(push_after_save(nixos_dir))
    return result


# ── Validation ─────────────────────────────────────────────────────────────────

def run_enabled_validation(
    nixos_dir: str,
    config: dict | None,
    host: str | None = None,
) -> list[dict]:
    """Run all enabled validation rules and return a list of finding dicts."""
    from . import validator as _val
    cfg_settings  = config_manager.load_config_settings(nixos_dir)
    enabled_rules = cfg_settings.get("validation_rules") or _val.default_validation_rules()
    findings = _val.run_validation(nixos_dir, enabled_rules, config or {}, host=host)
    _record_host_check(nixos_dir, host, findings)
    return findings


def _record_host_check(
    nixos_dir: str,
    host: str | None,
    findings: list[dict],
) -> None:
    """
    Remember that the host-local rules ran on this machine for this config state.

    Only the host NiCo currently runs on can be recorded – the host-local rules
    read the running system, so a result for any other host would be wrong.
    The entry is written to config.json (it travels with the config, which is
    the whole point: other machines get to see what is still unchecked), but
    only when fingerprint or result actually changed, so routine validation
    runs do not produce git noise.
    """
    from . import validator as _val

    this_host = _val.running_host()
    if not this_host:
        return
    known = config_manager.scan_hosts(nixos_dir)
    if len(known) < 2:
        return                      # single-host configs never report pending hosts
    if this_host not in known:
        return                      # running machine is not part of this config
    if host and host != this_host:
        return                      # a different host was inspected

    local_ids = {r.id for r in _val.ALL_RULES if r.host_local}
    severities = [f.get("severity") for f in findings if f.get("rule_id") in local_ids]
    result = "error" if "error" in severities else \
             "warn" if "warning" in severities else "ok"

    entry = {
        "at": datetime.now().replace(microsecond=0).isoformat(),
        "fp": _val.host_fingerprint(nixos_dir, this_host),
        "result": result,
    }
    try:
        stored   = config_manager.load_config_settings(nixos_dir).get("host_checks") or {}
        previous = stored.get(this_host) or {}
        if previous.get("fp") == entry["fp"] and previous.get("result") == entry["result"]:
            return                  # nothing changed – leave config.json alone
        stored[this_host] = entry
        config_manager.save_config_settings(nixos_dir, {"host_checks": stored})
    except Exception:
        pass                        # a failed bookkeeping write must not break validation


# ── Nix-Brick into the panel (Gegenprobe phase 4, 2026-11-19) ──────────────────

def adopt_brick(nixos_dir: str, rel: str, name: str) -> str:
    """Take a Nix-Brick into the form, if the form writes exactly the same.

    The brick is read like an import, the file written on trial without it,
    and compared with the file as it is (fidelity.compare): every statement
    of the brick must come back with the same value, nothing else in the file
    may change. All or nothing. Returns the new text after writing it; raises
    ValueError with an error code, or fidelity.NotFaithful with the paths
    that would change. No checkpoint here – the route makes it first.

    configuration.nix and host files only: the Home Manager panel patches
    single lines and never regenerates its file from the form.
    """
    from .brix import is_reserved_brick
    target = _resolve_config_rel(Path(nixos_dir).resolve(), rel)
    content = target.read_text(encoding="utf-8")
    host = _host_of(nixos_dir, rel)
    if rel != "configuration.nix" and not host:
        raise ValueError("ERR_ADOPT_FILE")
    if file_in_raw_mode(target) or file_unmappable(nixos_dir, rel, content):
        raise ValueError("ERR_NOT_MAPPABLE")
    blocks = extract_brick_blocks(content)
    block = blocks.get(name)
    if block is None:
        raise ValueError("ERR_BRICK_NOT_FOUND")
    if is_reserved_brick(name) or block.get("inactive"):
        raise ValueError("ERR_BRICK_RESERVED")
    body = brick_body(block["text"])
    recognized = importer.parse_config("{ config, pkgs, lib, ... }:\n{\n" + body + "\n}\n")
    if not recognized:
        raise fidelity.NotFaithful(fidelity.leaves(
            "{ config, pkgs, lib, ... }:\n{\n" + body + "\n}\n") or {"?"})
    if host:
        data = config_manager.load_host_config(nixos_dir, host) or {}
        hw = (target.parent / "hardware-configuration.nix").is_file()
        render = lambda d: generator.generate_host_nix(d, host, hw)  # noqa: E731
    else:
        data = config_manager.load_config(nixos_dir)
        render = generator.generate_configuration_nix
    trial = dict(data)
    trial["brick_blocks"] = {k: v for k, v in (data.get("brick_blocks") or {}).items()
                             if k != name}
    trial.update(recognized)
    text = render(trial)
    fidelity.require_faithful(content, text)
    # Comments would be lost: the form has no place for them. Asked after
    # the comparison, so a brick with a suggestion still commented out is
    # refused for what it is – the panel would write more – not for its
    # comments. NiCo's own suggestion line does not count.
    plain = "\n".join(l for l in body.splitlines() if l.strip() != fidelity.HINT_LINE)
    lines = lambda t: [l.rstrip() for l in t.splitlines() if l.strip()]  # noqa: E731
    if lines(importer._strip_nix_comments(plain)) != lines(plain):
        raise ValueError("ERR_ADOPT_COMMENTS")
    duplicates = validator.duplicate_attrs_in(text)
    if duplicates:
        raise config_manager.DuplicateAttrError(duplicates)
    atomic.write_text(target, text)
    return text
