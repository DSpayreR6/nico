def list_config_tree(nixos_dir: str) -> dict:
    """Return the visible config tree, matching the web UI rules."""
    root = Path(nixos_dir).resolve()
    cfg_settings = config_manager.load_config_settings(nixos_dir)
    hm_dir = cfg_settings.get("hm_dir", "home").strip() or "home"
    app_settings = config_manager.get_app_settings()
    show_flake_lock = bool(app_settings.get("show_flake_lock", False))

    def _classify_by_path(item: Path) -> str | None:
        rel = item.relative_to(root)
        parts = rel.parts
        if len(parts) >= 2 and parts[0] == hm_dir:
            return "hm"
        return classify_filename(item.name)

    def _build_tree(directory: Path) -> list[dict]:
        entries: list[dict] = []
        try:
            items = sorted(directory.iterdir(), key=lambda p: (p.is_file(), p.name.lower()))
        except PermissionError:
            return entries
        for item in items:
            if item.name.startswith(".") or (item.name == "nico" and item.is_dir()):
                continue
            # Never descend into directory symlinks: e.g. nixos-rebuild's
            # ./result -> /nix/store/...-nixos-system-... would pull the whole
            # system closure (thousands of dirs) into the tree.
            if item.is_symlink() and item.is_dir():
                continue
            rel_path = str(item.relative_to(root))
            if item.is_dir():
                entries.append({
                    "name": item.name,
                    "type": "dir",
                    "path": rel_path,
                    "children": _build_tree(item),
                })
            elif item.suffix == ".nix":
                entries.append({
                    "name": item.name,
                    "type": "file",
                    "path": rel_path,
                    "file_type": _FILENAME_TYPE_HINTS.get(item.name) or _classify_by_path(item),
                })
            elif item.name == "flake.lock" and show_flake_lock:
                entries.append({
                    "name": item.name,
                    "type": "file",
                    "path": rel_path,
                    "file_type": "flk",
                })
        return entries

    return {"tree": _build_tree(root), "root": str(root)}


def brick_blocks_for_file(nixos_dir: str, rel_path: str) -> dict[str, dict]:
    """Return the Nix bricks of one config file, read from disk.

    One source for every file. The brick lists in /api/config only ever cover
    configuration.nix, flake.nix and a legacy root home.nix, so dialogs that
    picked one of those showed the wrong bricks for host, module and HM files.
    """
    rel = (rel_path or "").strip()
    if not rel:
        raise ValueError("ERR_NO_PATH")

    root = Path(nixos_dir).resolve()
    target = _resolve_config_rel(root, rel)

    if target.suffix not in _WRITABLE_SUFFIXES:
        raise ValueError("ERR_FILE_TYPE")
    if not target.exists():
        raise FileNotFoundError("ERR_FILE_NOT_FOUND")

    return extract_brick_blocks(target.read_text(encoding="utf-8"))


def read_config_file(nixos_dir: str, rel_path: str, *, persist_stamp: bool = True) -> dict:
    """Read a config-relative file with the same normalization rules as the web UI.
    persist_stamp: write type stamps back to disk (endpoints pass False for
    requests without a valid CSRF token, so cross-site GETs never write)."""
    rel = (rel_path or "").strip()
    if not rel:
        raise ValueError("ERR_NO_PATH")

    root = Path(nixos_dir).resolve()
    target = _resolve_config_rel(root, rel)

    if target.suffix not in _READABLE_SUFFIXES:
        raise ValueError("ERR_FILE_TYPE")
    if not target.exists():
        raise FileNotFoundError("ERR_FILE_NOT_FOUND")

    content = target.read_text(encoding="utf-8")

    if target.name == "flake.lock":
        return {"content": content, "path": rel, "file_type": "flk", "writable": False}

    hint_type = _FILENAME_TYPE_HINTS.get(target.name)
    cfg_settings = config_manager.load_config_settings(nixos_dir)
    hm_dir = cfg_settings.get("hm_dir", "home").strip() or "home"
    rel_parts = Path(rel).parts
    path_type = "hm" if len(rel_parts) >= 2 and rel_parts[0] == hm_dir else None

    # Before any stamp: set_type_in_content() below recomputes the hash and
    # would make a file changed outside look as if NiCo had written it.
    outside = outside_status(nixos_dir, rel, content)
    mode = get_panel_mode(content) or \
        config_manager.load_config_settings(nixos_dir).get("panel_default", "p")
    if outside:
        persist_stamp = False

    ftype = get_nico_type(content)
    if ftype == "":
        stamp = hint_type or path_type or classify_filename(target.name) or "nd"
        content = insert_type(content, stamp)
        if persist_stamp:
            try:
                atomic.write_text(target, content)
            except OSError:
                pass
        ftype = stamp
    elif ftype is not None:
        override = hint_type or path_type
        if override and override != ftype:
            # insert_type() only handles legacy headers without type – a typed
            # header must be rewritten (incl. hash) via set_type_in_content().
            content = set_type_in_content(content, override)
            if persist_stamp:
                try:
                    atomic.write_text(target, content)
                except OSError:
                    pass
            ftype = override

    # Not for a file changed outside: the user is about to be asked whether
    # it may be restructured, and has to see it as it is.
    if ftype == "hm" and not outside:
        try:
            content, _ = normalize_hm_content(content)
        except Exception:
            pass

    return {
        "content": content,
        "path": rel,
        "file_type": ftype,
        # 'modified' / 'no_hash' / None – see outside_status().
        "outside": outside,
        "panel_mode": mode,
        "writable": target.suffix in _WRITABLE_SUFFIXES,
        # The interface shows such a file in the raw editor instead of a form.
        "unmappable": file_unmappable(nixos_dir, rel, content, ftype or path_type),
    }


def write_raw_config_file(
    nixos_dir: str,
    rel_path: str,
    content: str,
    *,
    label: str = "",
    commit: bool = True,
    force: bool = False,
) -> dict:
    """Write a raw .nix file inside the config directory.

    Raises NestedBricksError when the new content introduces a nested brick and
    force is not set.  Unlike the brick routes this is a question, not a
    refusal: in the raw editor the markers are visible and keeping them can be
    deliberate, and vorgaben.txt forbids discarding foreign Nix content.
    """
    rel = (rel_path or "").strip()
    if not rel:
        raise ValueError("ERR_NO_PATH")

    root = Path(nixos_dir).resolve()
    target = _resolve_config_rel(root, rel)

    if target.suffix not in _WRITABLE_SUFFIXES:
        raise ValueError("ERR_FILE_TYPE")

    cfg_settings = config_manager.load_config_settings(nixos_dir)
    hm_dir = cfg_settings.get("hm_dir", "home").strip() or "home"
    rel_parts = Path(rel).parts
    is_hm_path = len(rel_parts) >= 2 and rel_parts[0] == hm_dir
    if is_hm_path or classify_filename(target.name) == "hm":
        content, _ = normalize_hm_content(content)

    previous = ""
    if target.exists():
        try:
            previous = target.read_text(encoding="utf-8")
        except OSError:
            previous = ""
    if not force:
        introduced = new_nested_bricks(previous, content)
        if introduced:
            raise NestedBricksError(introduced)

    atomic.write_text(target, content)

    skipped_large: list[str] = []
    if commit:
        try:
            _, _, skipped_large = git_manager.auto_commit(nixos_dir, label=label)
        except Exception:
            pass

    result: dict = {"success": True, "written": [rel]}
    nested = [{**f, "file": rel} for f in find_nested_bricks(content)]
    if nested:
        # Already on disk before this write – not refused, but the inner brick
        # is invisible to NiCo, so it must not stay unmentioned either.
        result["nested"] = nested
    if skipped_large:
        # Left out of the commit for being oversized – never let that pass
        # unmentioned, the user would believe everything was saved to git.
        result["skipped_large"] = skipped_large
    result.update(push_after_save(nixos_dir))
    return result


def push_after_save(nixos_dir: str) -> dict:
    """Upload after a save, if both switches ask for it. Extra response fields.

    One place for the decision, because it was written three times and the
    copies drifted: the form write path checked `push_after_save` alone and
    uploaded with "Git-Sync" switched off - a silent remote action against an
    explicit setting, which vorgaben.txt rules out. The two switches sit on
    different levels on purpose: `git_sync` belongs to this machine (app
    settings), `push_after_save` travels with the config, so a config carrying
    push_after_save=true reaches a machine that wants to be left alone.
    """
    out: dict = {}
    try:
        if not config_manager.get_app_settings().get("git_sync", True):
            return out
        if not config_manager.load_config_settings(nixos_dir).get("push_after_save"):
            return out
        ok, msg, code = git_manager.git_push(nixos_dir)
        out["pushed"] = ok
        out["push_error"] = "" if ok else msg
        out["push_error_code"] = "" if ok else code
    except Exception:
        pass
    return out


