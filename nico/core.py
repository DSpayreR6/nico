def clean_nix_error(raw: str, tmpfile: str) -> str:
    """Sanitize nix error output: replace temp path, strip boilerplate."""
    cleaned = raw.replace(tmpfile, "<config>")
    lines   = cleaned.splitlines()
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join(lines)


